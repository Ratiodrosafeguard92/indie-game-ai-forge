"""Stage 7: emit a Godot 4 project skeleton.

Writes project.godot, a main scene, and per-level .tscn stubs.
Safe to re-run: overwrites only files it owns.
"""
from __future__ import annotations

import json
from pathlib import Path

from forge_core.job import Job
from forge_models.game_project import GameProject
from forge_output.base import EmitReport


class GodotDriver:
    name = "output.driver"
    requires = ("output.manifest",)

    def run(self, job: Job) -> Job:
        project: GameProject = job.ctx.scratch["project"]
        dest: Path = job.ctx.scratch["env"].run_dir / "game"
        report = self.emit(project, dest)
        job.ctx.scratch["emit_report"] = report
        return job

    def emit(self, project: GameProject, dest: Path) -> EmitReport:
        dest.mkdir(parents=True, exist_ok=True)
        written = 0

        (dest / "project.godot").write_text(_project_godot(project), encoding="utf-8")
        written += 1

        scenes = dest / "scenes"
        scenes.mkdir(exist_ok=True)
        for lvl in project.levels:
            (scenes / f"{lvl.id}.tscn").write_text(_scene(lvl), encoding="utf-8")
            written += 1

        (dest / "forge_manifest.json").write_text(
            json.dumps(project.to_manifest(), indent=2), encoding="utf-8"
        )
        written += 1
        return EmitReport(driver="godot", files_written=written, dest=dest)


def _project_godot(project: GameProject) -> str:
    return (
        "; Engine configuration file.\n"
        "; Generated by indie-game-ai-forge\n\n"
        "config_version=5\n\n"
        "[application]\n"
        f'config/name="{project.title}"\n'
        'run/main_scene="res://scenes/Main.tscn"\n'
        "config/features=PackedStringArray(\"4.3\")\n"
    )


def _scene(lvl) -> str:
    return (
        "[gd_scene format=3]\n\n"
        f"[node name=\"{lvl.id}\" type=\"Node2D\"]\n"
        f"; kind={lvl.kind} difficulty={lvl.difficulty}\n"
        f"; connects_to={','.join(lvl.connects_to) or 'none'}\n"
    )